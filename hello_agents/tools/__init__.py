# [概念] ★ 包导入的时机：这一行（以及下面每一行）都在**模块第一次被导入时**执行，
#        之后 Python 把它缓存进 sys.modules，再 import 就直接拿缓存，不会重跑。
# [机制] 所以这个文件其实是「包的门面 + 一份导入清单」，它在被任何人使用之前就已经跑完了。
# [易错] 反过来说：这里写的任何导入都会**无条件**发生。哪怕你只想用 registry，
#        下面这些统统会被拖进来（含它们的第三方依赖）—— 代价见文件末尾的实测。
