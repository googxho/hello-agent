# ===== 文件导读 =====
# [职责] 包的门面：把这个包里值得对外用的名字，一次性搬到 hello_agents.tools 这一层。
#        于是外面可以写 from hello_agents.tools import Tool，而不用写 from ...base import Tool。
# [位置] 顶层。任何 import hello_agents.tools.xxx 的动作都会先执行这个文件（下面有实测）。
# [阅读顺序] ① 前几行的分块导入（每块一个注释标题）
#            → ② __all__（它到底管什么、不管什么）
#            → ③ 回到开头，看包导入的时机与代价。
# [本文件新概念] ① 包的 __init__.py 何时执行　② 导入子模块会先执行所有父包
#                ③ __all__ 只影响 import *　④ 显式相对导入 vs 绝对导入　⑤ 「慷慨导出」的代价。
# [实测] 导入本包的代价约 2.2 秒，而且不管你导多深都一样：
#        import hello_agents                          2.22s
#        import hello_agents.tools                    2.27s
#        import hello_agents.tools.base               2.19s
#        import hello_agents.tools.builtin.win_rate_tool  2.17s
# ===================
