# [职责] 把多个工具按固定顺序串起来：上一步的输出，变成下一步的输入。
# [位置] tools/ 包里的另一个旁支 —— 和 async_executor 一样，没有任何 Agent 调用它，
#        只在 tools/__init__.py 的导出列表里出现。Agent 想串工具，走的是 ReAct 那种「模型自己决定下一步」。
# [阅读顺序] ① ToolChain.__init__ / add_step（链长什么样：只是一张「步骤表」）
#            → ② execute（唯一的执行入口，重点看第 65 行的模板替换和第 75 行的死代码）
#            → ③ ToolChainManager（给链再套一层管理器）
#            → ④ 两个 create_* 便捷函数（重点：它们引用的工具名根本不存在）。
# [本文件新概念] ① 模板字符串与 str.format 变量替换　② 链式编排（数据在步骤间流动）
#                ③ 组合：链只存「说明」，不存工具本体　④ or 短路做默认值　⑤ 异常边界该画在哪。
# [实测] 两个便捷函数造出来的链，跑起来一定失败但日志全绿 —— 见 create_research_chain 的注释。
